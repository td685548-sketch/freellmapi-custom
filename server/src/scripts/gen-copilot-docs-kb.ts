/**
 * gen-copilot-docs-kb — regenerate the Setup Copilot docs knowledge base.
 *
 * The runtime image does not ship docs/, so the docs the Copilot may quote are
 * baked into `custom/support-setup-copilot/kb/docs.generated.ts`. A test
 * regenerates the content in memory and fails when the committed file is stale.
 *
 * Usage: tsx src/scripts/gen-copilot-docs-kb.ts [--check]
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(HERE, '../../..');
const DOCS_DIR = path.join(REPO_ROOT, 'docs');
export const GENERATED_FILE = path.resolve(HERE, '../custom/support-setup-copilot/kb/docs.generated.ts');

const TOP_LEVEL = ['ai-platform.md', 'x-gateway.md', 'x-gateway-quota.md', 'x-gateway-subscriptions.md', 'context-budget.md'];
const SKIP_DIRS = new Set(['testing', 'desktop']);
const MAX_CHARS = 1400;
const MIN_CHARS = 80;

export interface DocsKbChunk {
  id: string;
  file: string;
  title: string;
  text: string;
}

function listMarkdown(dir: string, rel = ''): string[] {
  const out: string[] = [];
  for (const entry of fs.readdirSync(path.join(dir, rel), { withFileTypes: true })) {
    const relPath = rel ? `${rel}/${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      if (SKIP_DIRS.has(entry.name)) continue;
      out.push(...listMarkdown(dir, relPath));
    } else if (entry.name.endsWith('.md') && !/^CHANGELOG/i.test(entry.name)) {
      out.push(relPath);
    }
  }
  return out.sort();
}

function clean(markdown: string): string {
  return markdown
    .replace(/\r\n/g, '\n')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/!\[[^\]]*\]\([^)]*\)/g, '')
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
    .replace(/<[^>]+>/g, '')
    .replace(/```[\s\S]*?```/g, (block) => (block.length > 500 ? '[code example omitted]' : block))
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

export function chunkMarkdown(file: string, raw: string): DocsKbChunk[] {
  const text = clean(raw);
  const sections: Array<{ heading: string; body: string[] }> = [{ heading: '', body: [] }];
  let docTitle = path.basename(file, '.md');
  for (const line of text.split('\n')) {
    const h = /^(#{1,3})\s+(.+?)\s*$/.exec(line);
    if (h) {
      if (h[1] === '#' && sections.length === 1 && sections[0]!.body.length === 0) {
        docTitle = h[2]!;
        sections[0]!.heading = h[2]!;
      } else {
        sections.push({ heading: h[2]!, body: [] });
      }
    } else {
      sections[sections.length - 1]!.body.push(line);
    }
  }
  const chunks: DocsKbChunk[] = [];
  let n = 0;
  for (const s of sections) {
    const body = s.body.join('\n').trim();
    if (body.length < MIN_CHARS) continue;
    const title = s.heading && s.heading !== docTitle ? `${docTitle} — ${s.heading}` : docTitle;
    // Split long sections on paragraph boundaries.
    const paragraphs = body.split(/\n{2,}/);
    let buf = '';
    const flush = (): void => {
      const t = buf.trim();
      if (t.length >= MIN_CHARS) {
        n += 1;
        chunks.push({ id: `doc:${file}#${n}`, file: `docs/${file}`, title, text: t });
      }
      buf = '';
    };
    for (const p of paragraphs) {
      const piece = p.length > MAX_CHARS ? `${p.slice(0, MAX_CHARS - 1)}…` : p;
      if (buf && buf.length + piece.length + 2 > MAX_CHARS) flush();
      buf += (buf ? '\n\n' : '') + piece;
    }
    flush();
  }
  return chunks;
}

export function collectDocsKb(): DocsKbChunk[] {
  const files = [...listMarkdown(path.join(DOCS_DIR, 'en')).map((f) => `en/${f}`), ...TOP_LEVEL.filter((f) => fs.existsSync(path.join(DOCS_DIR, f)))];
  const all: DocsKbChunk[] = [];
  for (const file of files) {
    all.push(...chunkMarkdown(file, fs.readFileSync(path.join(DOCS_DIR, file), 'utf8')));
  }
  return all;
}

export function renderGeneratedFile(chunks: readonly DocsKbChunk[]): string {
  return [
    '// GENERATED by src/scripts/gen-copilot-docs-kb.ts — do not edit by hand.',
    '// Regenerate: npm run kb:docs -w server',
    "import type { DocsKbChunk } from './docs-kb-types.js';",
    '',
    `export const DOCS_KB: readonly DocsKbChunk[] = [\n${chunks.map((c) => JSON.stringify(c)).join(',\n')},\n];`,
    '',
  ].join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const rendered = renderGeneratedFile(collectDocsKb());
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(GENERATED_FILE) ? fs.readFileSync(GENERATED_FILE, 'utf8') : '';
    if (current !== rendered) {
      console.error('docs.generated.ts is stale — run: npm run kb:docs -w server');
      process.exit(1);
    }
    console.log('docs.generated.ts is up to date');
  } else {
    fs.writeFileSync(GENERATED_FILE, rendered);
    console.log(`wrote ${GENERATED_FILE} (${rendered.length} bytes)`);
  }
}
