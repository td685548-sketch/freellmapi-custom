import { Router, type Request, type Response } from 'express';
import { permissionGranted } from '@freellmapi/shared/permissions.js';
import { validateUserApiKey } from '../../services/user-keys.js';
import { getUsableXGatewayKeys, accountModels } from '../provider-accounts/store.js';
import { getXGatewayProvider } from '../provider-accounts/catalog.js';
import { getConfigSnapshot } from './config.js';
import {
  validateXGatewayClientKey,
  isModelAllowedForKey,
  type ValidatedXGatewayClientKey,
} from './client-keys.js';

export const xGatewayOllamaRouter = Router();

// CORS preflight and headers
xGatewayOllamaRouter.use((req, res, next) => {
  res.setHeader('Access-Control-Allow-Origin', '*');
  res.setHeader('Access-Control-Allow-Methods', 'GET, POST, OPTIONS');
  res.setHeader('Access-Control-Allow-Headers', '*');
  if (req.method === 'OPTIONS') {
    res.status(204).end();
    return;
  }
  next();
});

function extractOllamaKey(req: Request): string | undefined {
  const auth = req.headers['authorization'];
  if (typeof auth === 'string' && auth.startsWith('Bearer ')) {
    return auth.slice(7).trim();
  }
  const xApiKey = req.headers['x-api-key'];
  if (typeof xApiKey === 'string' && xApiKey.trim()) {
    return xApiKey.trim();
  }
  const queryKey = req.query['key'] ?? req.query['token'];
  if (typeof queryKey === 'string' && queryKey.trim()) {
    return queryKey.trim();
  }
  return undefined;
}

function resolveOllamaUser(req: Request): ValidatedXGatewayClientKey | null {
  const token = extractOllamaKey(req);
  if (!token) return null;
  return validateXGatewayClientKey(token) ?? (validateUserApiKey(token) as ValidatedXGatewayClientKey | null);
}

const MODIFIED_AT = new Date().toISOString();

function formatOllamaModel(id: string, family: string) {
  return {
    name: id,
    model: id,
    modified_at: MODIFIED_AT,
    size: 4000000000,
    digest: `sha256:${Buffer.from(id).toString('hex').padEnd(64, '0').slice(0, 64)}`,
    details: {
      parent_model: '',
      format: 'gguf',
      family: family || 'custom',
      families: [family || 'custom'],
      parameter_size: '7B',
      quantization_level: 'Q4_K_M',
    },
  };
}

function handleTags(req: Request, res: Response): void {
  res.setHeader('Access-Control-Allow-Origin', '*');
  const user = resolveOllamaUser(req);
  if (user && !permissionGranted(user, 'use_x_gateway')) {
    res.status(403).json({ error: 'Permission denied: use_x_gateway required' });
    return;
  }

  const snapshot = getConfigSnapshot();
  const models: Array<ReturnType<typeof formatOllamaModel>> = [];
  const seen = new Set<string>();

  // Combos
  for (const combo of snapshot.combos) {
    const id = `combo:${combo.name}`;
    if (!seen.has(id)) {
      if (!user?.access?.restricted || isModelAllowedForKey(user.access, id)) {
        seen.add(id);
        models.push(formatOllamaModel(id, 'combo'));
      }
    }
  }

  // Account models
  for (const account of getUsableXGatewayKeys()) {
    const providerEntry = getXGatewayProvider(account.provider);
    const alias = providerEntry?.alias ?? account.provider;
    for (const m of accountModels(account)) {
      const prefixed = `${alias}/${m.id}`;
      if (!seen.has(prefixed)) {
        if (!user?.access?.restricted || isModelAllowedForKey(user.access, prefixed)) {
          seen.add(prefixed);
          models.push(formatOllamaModel(prefixed, alias));
        }
      }
      if (!seen.has(m.id)) {
        if (!user?.access?.restricted || isModelAllowedForKey(user.access, m.id)) {
          seen.add(m.id);
          models.push(formatOllamaModel(m.id, alias));
        }
      }
    }
  }

  // If empty, supply fallback auto
  if (models.length === 0) {
    models.push(formatOllamaModel('auto', 'x-gateway'));
  }

  res.json({ models });
}

function handleVersion(_req: Request, res: Response): void {
  res.setHeader('Access-Control-Allow-Origin', '*');
  res.json({ version: '0.5.1' });
}

function handleShow(req: Request, res: Response): void {
  res.setHeader('Access-Control-Allow-Origin', '*');
  const body = (req.body && typeof req.body === 'object') ? req.body as Record<string, unknown> : {};
  const model = typeof body.model === 'string' ? body.model : (typeof body.name === 'string' ? body.name : 'auto');

  res.json({
    license: 'Apache-2.0',
    modelfile: `# Modelfile generated by X Gateway\nFROM ${model}`,
    parameters: 'stop "<|endoftext|>"',
    template: '{{ .Prompt }}',
    details: {
      parent_model: '',
      format: 'gguf',
      family: 'custom',
      families: ['custom'],
      parameter_size: '7B',
      quantization_level: 'Q4_K_M',
    },
  });
}

xGatewayOllamaRouter.get('/api/tags', handleTags);
xGatewayOllamaRouter.get('/tags', handleTags);
xGatewayOllamaRouter.get('/api/version', handleVersion);
xGatewayOllamaRouter.get('/version', handleVersion);
xGatewayOllamaRouter.post('/api/show', handleShow);
xGatewayOllamaRouter.post('/show', handleShow);
